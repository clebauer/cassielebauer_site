// Generates data/countries.js and data/mapData.js for the quiz component.
// Run: node build.mjs   (needs world-atlas, topojson-client, d3-geo, world-countries)
import { createRequire } from "node:module";
import fs from "node:fs";
import { feature } from "topojson-client";
import { presimplify, simplify, quantile } from "topojson-simplify";
import { geoPath, geoNaturalEarth1 } from "d3-geo";
const require = createRequire(import.meta.url);
const wc = require("world-countries");
const atlas = require("world-atlas/countries-50m.json");
const C = require("./continents.json");

const OUT = "../data";
fs.mkdirSync(OUT, { recursive: true });

// ---------- normalisation (must match src/quizLogic.js) ----------
const norm = (s) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/&/g, " and ")
    .replace(/['’`]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .split(" ")
    .map((t) => (t === "st" ? "saint" : t))
    .join(" ")
    .replace(/^the /, "");

// ---------- countries ----------
const manualCca2 = {
  "Cabo Verde": "CV",
  "Democratic Republic of the Congo": "CD",
  "Cote d'Ivoire": "CI",
  "Sao Tome and Principe": "ST",
  Turkey: "TR",
};
const byName = Object.fromEntries(wc.map((c) => [c.name.common.toLowerCase(), c]));
const byCca2 = Object.fromEntries(wc.map((c) => [c.cca2, c]));

const manualAliases = {
  "United States": ["usa", "us", "u.s.", "u.s.a.", "america", "united states of america"],
  "United Kingdom": ["uk", "u.k.", "great britain", "britain"],
  "United Arab Emirates": ["uae"],
  Czechia: ["czech republic"],
  Eswatini: ["swaziland"],
  "Cote d'Ivoire": ["ivory coast"],
  "Cabo Verde": ["cape verde"],
  "Democratic Republic of the Congo": ["dr congo", "drc", "congo kinshasa", "democratic republic of congo", "congo democratic republic"],
  "Republic of the Congo": ["congo", "congo brazzaville", "republic of congo"],
  "Timor-Leste": ["east timor"],
  Myanmar: ["burma"],
  "North Macedonia": ["macedonia"],
  Turkey: ["turkiye"],
  Netherlands: ["holland", "the netherlands"],
  "Vatican City": ["vatican", "holy see"],
  Micronesia: ["federated states of micronesia"],
  "Sao Tome and Principe": ["sao tome"],
  "Bosnia and Herzegovina": ["bosnia"],
  "Trinidad and Tobago": ["trinidad"],
  "Antigua and Barbuda": ["antigua"],
  "Saint Kitts and Nevis": ["saint kitts"],
  "Saint Vincent and the Grenadines": ["saint vincent"],
  Russia: ["russian federation"],
  "South Korea": ["korea south", "republic of korea"],
  "North Korea": ["korea north", "dprk"],
  Palestine: ["state of palestine"],
  Taiwan: ["republic of china"],
  Ireland: ["republic of ireland"],
  "Papua New Guinea": ["png"],
};

const latin = /^[\x20-\x7EÀ-ɏ]+$/;
const countries = [];
const ccn3ToId = {};
for (const [continent, list] of Object.entries(C)) {
  for (const name of list) {
    const rec = byName[name.toLowerCase()] ?? byCca2[manualCca2[name]];
    if (!rec) throw new Error("no match " + name);
    const id = rec.cca3;
    const aliases = new Set();
    [rec.name.common, rec.name.official, ...rec.altSpellings, ...(manualAliases[name] ?? [])].forEach((a) => {
      if (!a) return;
      const n = norm(a);
      const whitelisted = (manualAliases[name] ?? []).includes(a);
      if (!whitelisted && (a.length <= 3 || !latin.test(a))) return;
      if (n) aliases.add(n);
    });
    aliases.add(norm(name));
    countries.push({ id, name: rec.name.common === name ? name : name, continent, aliases: [...aliases] });
    if (rec.ccn3) ccn3ToId[rec.ccn3] = id;
  }
}
// drop aliases that collide with another country's primary alias
const owners = {};
countries.forEach((c) => c.aliases.forEach((a) => (owners[a] ??= []).push(c.id)));
const primary = new Set(countries.map((c) => norm(c.name)));
for (const c of countries) {
  c.aliases = c.aliases.filter((a) => {
    const o = owners[a];
    if (o.length === 1) return true;
    const keep = norm(c.name) === a || !primary.has(a);
    if (!keep) console.log("dropped alias", a, "from", c.name);
    else if (norm(c.name) !== a) console.log("shared alias", a, o);
    return keep;
  });
}
// pretty display names
const display = { "Cote d'Ivoire": "Côte d'Ivoire", "Sao Tome and Principe": "São Tomé and Príncipe" };
const out = countries.map((c) => ({ id: c.id, name: display[c.name] ?? c.name, continent: c.continent, aliases: c.aliases }));
fs.writeFileSync(
  `${OUT}/countries.js`,
  `// Generated by tools/build.mjs. ${out.length} countries.\n// "aliases" are pre-normalised (see normalize() in quizLogic.js).\nexport const CONTINENTS = ${JSON.stringify(["North America", "South America", "Oceania", "Asia", "Europe", "Africa"])};\nexport const COUNTRIES = ${JSON.stringify(out)};\n`
);

// ---------- map ----------
const territoryContinent = (rec) => {
  if (!rec) return null;
  if (rec.region === "Antarctic") return null;
  if (rec.region === "Americas") return rec.subregion === "South America" ? "South America" : "North America";
  if (["Africa", "Asia", "Europe", "Oceania"].includes(rec.region)) return rec.region;
  return null;
};
const byCcn3 = Object.fromEntries(wc.filter((c) => c.ccn3).map((c) => [c.ccn3, c]));
const noIdContinent = { Somaliland: ["Africa", null], Kosovo: ["Europe", "XKX"], "N. Cyprus": ["Asia", null] };
// Kosovo's cca3 in world-countries:
const kosovo = wc.find((c) => c.cca2 === "XK");
noIdContinent.Kosovo[1] = kosovo.cca3;

const SIMPLIFY = Number(process.env.SIMPLIFY ?? 0.15); // fraction of detail to drop
const pre = presimplify(atlas);
const simp = simplify(pre, quantile(pre, SIMPLIFY));
const fc = feature(simp, simp.objects.countries);
const feats = fc.features.filter((f) => f.id !== "010"); // drop Antarctica
const projection = geoNaturalEarth1().fitExtent([[2, 2], [958, 498]], { type: "FeatureCollection", features: feats });
const gp = geoPath(projection).digits(1);

const items = []; // {id, c, d}
const territories = {}; // continent -> d[]
const idToContinent = Object.fromEntries(countries.map((c) => [c.id, c.continent]));
const addTerritory = (cont, d) => d && (territories[cont] ??= []).push(d);

for (const f of feats) {
  const ccn3 = f.id ? String(f.id).padStart(3, "0") : null;
  let id = ccn3 ? ccn3ToId[ccn3] : null;
  let cont = id ? idToContinent[id] : null;
  const nm = f.properties.name;
  if (!ccn3 && noIdContinent[nm]) {
    [cont, id] = noIdContinent[nm];
    if (id && !idToContinent[id]) id = null;
    if (id) cont = idToContinent[id];
  } else if (!id) {
    cont = territoryContinent(byCcn3[ccn3]);
  }
  if (nm === "France" && f.geometry.type === "MultiPolygon") {
    // split overseas pieces off so they highlight with their own continent
    const main = [];
    for (const poly of f.geometry.coordinates) {
      const [lon, lat] = poly[0][0];
      let where = "Europe";
      if (lon > -60 && lon < -45 && lat < 10) where = "South America";
      else if (lon < -55 && lat >= 10 && lat < 25) where = "North America";
      else if (lon > 30 && lat < 5) where = "Africa";
      if (where === "Europe") main.push(poly);
      else addTerritory(where, gp({ type: "MultiPolygon", coordinates: [poly] }));
    }
    items.push({ id, c: cont, d: gp({ type: "MultiPolygon", coordinates: main }) });
    continue;
  }
  const d = gp(f);
  if (!d) continue;
  if (id) items.push({ id, c: cont, d });
  else if (cont) addTerritory(cont, d);
  else items.push({ id: null, c: null, d }); // neutral land (e.g. Indian Ocean Ter.)
}
const terr = Object.entries(territories).map(([c, ds]) => ({ id: null, c, d: ds.join("") }));
const all = [...items, ...terr];
const missing = countries.filter((c) => !items.some((i) => i.id === c.id)).map((c) => c.name);
console.log("quiz countries with no shape on the map:", missing.length, missing.join(", "));
fs.writeFileSync(
  `${OUT}/mapData.js`,
  `// Generated by tools/build.mjs from Natural Earth (via world-atlas 50m). Natural Earth projection.\n// id = ISO alpha-3 of a quiz country (null for territories); c = continent (null = neutral land).\nexport const VIEWBOX = "0 0 960 500";\nexport const MAP_SHAPES = ${JSON.stringify(all)};\n`
);
console.log("shapes:", all.length, "bytes:", fs.statSync(`${OUT}/mapData.js`).size);
